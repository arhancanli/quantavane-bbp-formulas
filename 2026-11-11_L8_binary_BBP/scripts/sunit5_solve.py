"""Collect five-term relations among the exceptional S-units of Q(zeta_8) (from sunit5.py) and test whether
a target D-identity lies in their span.  Usage: python -I sunit5_solve.py exc.json target_spec out.json
target_spec: 're,im:coef;re,im:coef;...' numeric points (identity embedding) with rational coefficients."""
import sys, json, cmath, math
from fractions import Fraction as Fr
import sympy

def key(z):
    return (round(z.real, 9) + 0.0, round(z.imag, 9) + 0.0)

def main():
    exc = json.load(open(sys.argv[1]))
    pts = {}
    for e, (re, im) in exc:
        z = complex(re, im)
        pts[key(z)] = (tuple(e), z)
    # D-orbit canonicalisation: group generated by z->1-z (sign -1), z->1/z (sign -1), conj (sign -1)
    maps = [(lambda z: z, 1), (lambda z: 1 - 1 / z, 1), (lambda z: 1 / (1 - z), 1),
            (lambda z: 1 / z, -1), (lambda z: 1 - z, -1), (lambda z: z / (z - 1), -1)]
    def canon(z):
        if abs(z.imag) < 1e-10:
            return (None, 0)
        best = None
        for f, s in maps:
            v = f(z)
            for w, s2 in ((v, s), (v.conjugate(), -s)):
                k = key(w)
                if best is None or k < best[0]:
                    best = (k, s2)
        if best[0] not in pts:
            return None
        return best
    zs = [v[1] for v in pts.values()]
    rels = []
    seen = set()
    for x in zs:
        cx = canon(x)
        if cx is None:
            continue
        for y in zs:
            if abs(1 - x * y) < 1e-9:
                continue
            w4 = 1 - x * y
            if key(w4) not in pts and key(1 - w4) not in pts:
                continue
            args = [x, y, (1 - x) / (1 - x * y), w4, (1 - y) / (1 - x * y)]
            vec = {}
            ok = True
            for a in args:
                c = canon(a)
                if c is None:
                    ok = False
                    break
                if c[0] is None:
                    continue
                vec[c[0]] = vec.get(c[0], 0) + c[1]
            if not ok:
                continue
            vec = {k: v for k, v in vec.items() if v}
            if not vec:
                continue
            sig = tuple(sorted(vec.items()))
            if sig in seen:
                continue
            seen.add(sig)
            rels.append((vec, (x, y)))
    print("five-term relations:", len(rels), flush=True)
    target = {}
    for part in sys.argv[2].split(';'):
        pt, c = part.split(':')
        re, im = (float(t) for t in pt.split(','))
        cz = canon(complex(re, im))
        if cz is None:
            print("target point not in the set:", pt); return
        if cz[0] is None:
            continue
        target[cz[0]] = target.get(cz[0], 0) + Fr(c) * cz[1]
    keys = sorted(set(k for v, _ in rels for k in v) | set(target))
    M = sympy.Matrix([[v.get(k, 0) for k in keys] for v, _ in rels])
    t = sympy.Matrix([sympy.Rational(target.get(k, Fr(0)).numerator, target.get(k, Fr(0)).denominator) for k in keys])
    print("unknown classes:", len(keys), "rank:", M.rank(), flush=True)
    try:
        sol, params = M.T.gauss_jordan_solve(t)
    except ValueError:
        print("target NOT in span"); return
    sol = sol.subs({p: 0 for p in params})
    used = [(i, sol[i]) for i in range(len(rels)) if sol[i] != 0]
    print("TARGET IN SPAN; relations used:", len(used))
    out = []
    for i, c in used:
        v, (x, y) = rels[i]
        print(f"  coef {c}:  x = {x:.12f}, y = {y:.12f}")
        out.append({"coef": str(c), "x": [x.real, x.imag], "y": [y.real, y.imag]})
    json.dump(out, open(sys.argv[3], 'w'), indent=1)

if __name__ == '__main__':
    main()
