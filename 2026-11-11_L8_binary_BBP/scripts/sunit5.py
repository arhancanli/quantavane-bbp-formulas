"""Five-term relations among exceptional S-units of Q(zeta_8), S = primes above 2 and 3.

An exceptional S-unit x has x and 1-x both S-units.  For exceptional x, y with 1-xy an S-unit, the five
arguments of the Bloch-Wigner five-term relation are exceptional S-units.  We collect these relations
(at the identity embedding; real arguments give D = 0), canonicalise each argument under the 12-element
group generated by z -> 1-z, z -> 1/z and complex conjugation (D picks up a sign), and test whether a
target combination lies in their rational span.  Every relation used is then re-verified in exact
arithmetic.

S-unit generators: zeta_8 (torsion), eps = 1 + sqrt2, p2 = 1 - zeta_8, p3 = 1 + sqrt(-2), q3 = 1 - sqrt(-2).
"""
import sys, cmath, math, json, itertools
sys.path.insert(0, __file__.rsplit('/', 1)[0])
from fractions import Fraction as Fr
from cyclo import CycloField

K = CycloField(8)
z8 = cmath.exp(2j * math.pi / 8)
S2 = 2 ** 0.5
GEN_NUM = {'eps': 1 + S2, 'p2': 1 - z8, 'p3': 1 + 1j * S2, 'q3': 1 - 1j * S2}
# exact generators in Q(zeta_8): sqrt2 = t + t^-1 = t - t^3 ; sqrt(-2) = t + t^3
T = lambda k: K.zeta(k)
SQ2 = K.sub(T(1), T(3))
SQM2 = K.add(T(1), T(3))
GEN_EX = {'eps': K.add(K.one(), SQ2), 'p2': K.sub(K.one(), T(1)),
          'p3': K.add(K.one(), SQM2), 'q3': K.sub(K.one(), SQM2)}


def norm_num(w):
    """Norm Q(zeta_8)/Q numerically: product over embeddings zeta -> zeta^a, a in {1,3,5,7}.
    w given as exponent tuple (k, a_eps, a_p2, a_p3, a_q3) -> use exact repr instead."""
    raise NotImplementedError


def embed(ex, a):
    """Numeric value of exact element ex under zeta_8 -> zeta_8^a."""
    t = cmath.exp(2j * math.pi * a / 8)
    return sum(complex(float(c)) * t ** i for i, c in enumerate(ex))


def is_S_unit_exact(ex):
    """Norm of ex is +-2^i 3^j (exact rational check via product of conjugates, rounded)."""
    v = 1
    for a in (1, 3, 5, 7):
        v *= embed(ex, a)
    n = v.real
    if abs(v.imag) > 1e-6 * max(1, abs(n)) or abs(n) < 1e-9:
        return False
    # n should be rational with denominator a power of 2 and 3
    for num_try in (n, 1 / n):
        m = abs(num_try)
        r = round(m)
        if r > 0 and abs(m - r) < 1e-6 * max(1, m):
            while r % 2 == 0:
                r //= 2
            while r % 3 == 0:
                r //= 3
            if r == 1:
                # check the other side too (n or 1/n must be +-2^i3^j times such)
                return True
    # general rational p/q with p, q in <2,3>: try denominators 2^i3^j up to bounds
    for i in range(0, 25):
        for j in range(0, 16):
            d = 2 ** i * 3 ** j
            x = n * d
            r = round(x)
            if r != 0 and abs(x - r) < 1e-6 * max(1, abs(x)):
                rr = abs(r)
                while rr % 2 == 0:
                    rr //= 2
                while rr % 3 == 0:
                    rr //= 3
                return rr == 1
    return False


def power(ex, e):
    res = K.one()
    base = ex if e >= 0 else K.inv(ex)
    for _ in range(abs(e)):
        res = K.mul(res, base)
    return res


def main():
    A, B, C = (int(x) for x in sys.argv[1:4])
    out = sys.argv[4]
    # enumerate S-units x = zeta^k eps^a p2^b p3^c q3^d  numerically, keep exceptional ones
    gens = ['eps', 'p2', 'p3', 'q3']
    cand = []
    for k in range(8):
        for a in range(-A, A + 1):
            for b in range(-B, B + 1):
                for c in range(-C, C + 1):
                    for d in range(-C, C + 1):
                        x = z8 ** k * GEN_NUM['eps'] ** a * GEN_NUM['p2'] ** b * GEN_NUM['p3'] ** c * GEN_NUM['q3'] ** d
                        if abs(x) > 1e6 or abs(x) < 1e-6 or abs(1 - x) < 1e-9:
                            continue
                        # quick numeric test of 1-x being an S-unit: |norm| via embeddings needs exact; do numerically
                        cand.append(((k, a, b, c, d), x))
    print("S-units enumerated:", len(cand), flush=True)
    # numeric norm of 1-x requires the conjugates of x: x^(sigma_a) = zeta^{k a} * gens^sigma
    gen_conj = {}
    for g in gens:
        gen_conj[g] = {a: embed(GEN_EX[g], a) for a in (1, 3, 5, 7)}
    exc = []
    for e, x in cand:
        k, a, b, c, d = e
        nv = 1
        for s in (1, 3, 5, 7):
            xs = cmath.exp(2j * math.pi * k * s / 8) * gen_conj['eps'][s] ** a * gen_conj['p2'][s] ** b * gen_conj['p3'][s] ** c * gen_conj['q3'][s] ** d
            nv *= (1 - xs)
        n = nv.real
        if abs(n) < 1e-12:
            continue
        den = 2 ** max(0, -b) * 9 ** (max(0, -c) + max(0, -d))
        y = n * den
        M = round(y)
        ok = False
        if M != 0 and abs(y - M) < 1e-6 * max(1.0, abs(y)):
            M = abs(M)
            while M % 2 == 0:
                M //= 2
            while M % 3 == 0:
                M //= 3
            ok = (M == 1)
        if ok:
            exc.append((e, x))
    print("exceptional S-units:", len(exc), flush=True)
    json.dump([[list(e), [x.real, x.imag]] for e, x in exc], open(out, 'w'))


if __name__ == '__main__':
    main()
